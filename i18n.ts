export const getLocale = (language: AppLanguage): string => language === 'ru' ? 'ru-RU' : 'en-US';

export const hasRussianTranslation = (key: string): boolean => Object.hasOwn(RU, key);

export const translate = (
  language: AppLanguage,
  key: string,
  params: TranslationParams = {},
): string => {
  const template = language === 'ru' ? RU[key] ?? key : key;
  return Object.entries(params).reduce(
    (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
    template,
  );
};

export const useI18n = () => {
  const { state } = useAppStore();
  const language = state.uiPreferences.language;
  return useMemo(() => ({
    language,
    locale: getLocale(language),
    t: (key: string, params?: TranslationParams) => translate(language, key, params),
  }), [language]);
};
